def slugify(value: str) -> str:
    value = value.strip().lower()
    value = re.sub(r"[^a-z0-9\u4e00-\u9fff]+", "-", value)
    return value.strip("-") or "research-run"


def utc_now() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


def cmd_doctor(_: argparse.Namespace) -> int:
    print(f"root: {ROOT}")
    print(f"python: {sys.executable}")
    for command in ("pandoc", "git"):
        print(f"{command}: {shutil.which(command) or 'not found'}")
    print("status: ready for skill-driven research")
    return 0


def cmd_init(args: argparse.Namespace) -> int:
    config = Path(args.config).resolve()
    if not config.is_file():
        raise SystemExit(f"config not found: {config}")
    slug = args.slug or slugify(config.stem)
    run_dir = Path(args.out or ROOT / "runs" / slug).resolve()
    if run_dir.exists() and any(run_dir.iterdir()) and not args.force:
        raise SystemExit(f"run directory is not empty; use --force only when intended: {run_dir}")
    run_dir.mkdir(parents=True, exist_ok=True)
    shutil.copy2(config, run_dir / "request.yaml")
    shutil.copy2(TEMPLATE_DIR / "report.md", run_dir / "REPORT.md")
    shutil.copy2(TEMPLATE_DIR / "experiment-matrix.csv", run_dir / "experiment-matrix.csv")
    shutil.copy2(TEMPLATE_DIR / "data-points.csv", run_dir / "data-points.csv")
    shutil.copy2(TEMPLATE_DIR / "visual-plan.json", run_dir / "visual-plan.json")
    (run_dir / "sources.jsonl").write_text("", encoding="utf-8")
    (run_dir / "claims.jsonl").write_text("", encoding="utf-8")
    (run_dir / "evidence").mkdir(exist_ok=True)
    (run_dir / "source-assets").mkdir(exist_ok=True)
    figures_dir = run_dir / "figures"
    figures_dir.mkdir(exist_ok=True)
    (figures_dir / "figure-register.jsonl").write_text("", encoding="utf-8")
    (run_dir / "validation").mkdir(exist_ok=True)
    (run_dir / "plan.md").write_text(
        "# Research plan\n\nGenerated by researchctl. The Agent should replace this with a report-oriented question tree.\n",
        encoding="utf-8",
    )
    manifest = {
        "created_at": utc_now(),
        "run_dir": str(run_dir),
        "status": "initialized",
        "workflow_version": "0.3.0",
    }
    (run_dir / "run-manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(run_dir)
    return 0


